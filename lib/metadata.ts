import type { Metadata } from 'next'
import { site } from './site'

/** Per-route metadata: canonical URL, Open Graph and Twitter cards. The
    social image is public/social/<last path segment>.png, generated by
    `npm run social`. */
export function pageMetadata(
  title: string,
  description: string,
  path: string,
): Metadata {
  const slug = path === '/' ? 'home' : path.split('/').filter(Boolean).at(-1)
  const image = `/social/${slug}.png`
  const alt = `${title} · ${site.name}, ${site.role.toLowerCase()} in Toronto`
  return {
    title,
    description,
    alternates: { canonical: path },
    openGraph: {
      title,
      description,
      url: path,
      type: 'website',
      siteName: site.brand,
      locale: 'en_CA',
      images: [{ url: image, width: 1200, height: 630, alt }],
    },
    twitter: {
      card: 'summary_large_image',
      title,
      description,
      images: [{ url: image, alt }],
    },
  }
}
